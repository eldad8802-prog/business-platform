#!/usr/bin/env node
/**
 * sec(C) — generate ops/evidence/security-catalog-assert.sql from the repository's
 * migrations (the expected security catalog), so the Production evidence run
 * compares Production against what the repo says it should be — not against a
 * hand-maintained list that can drift.
 *
 *   node scripts/security/gen-security-catalog.mjs          # (re)write the SQL
 *   node scripts/security/gen-security-catalog.mjs --check  # exit 1 if stale
 *
 * Derived statically by replaying prisma/migrations/<dir>/migration.sql in order:
 *   - every table created (CREATE TABLE) and not dropped
 *   - ENABLE / DISABLE / FORCE / NO FORCE ROW LEVEL SECURITY per table
 *   - CREATE POLICY / DROP POLICY per table (static statements; policies created
 *     through dynamic SQL are not expected, so they can never cause a false FAIL)
 *   - every migration directory name (for the _prisma_migrations ledger)
 *   - the sec(C) composite tenant FKs and SECURITY DEFINER lookups, if present
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "../..");
const OUT = path.join(ROOT, "ops/evidence/security-catalog-assert.sql");
const migDir = path.join(ROOT, "prisma/migrations");

const strip = (s) => s.replace(/--[^\n]*/g, "");
const unq = (s) => s.replace(/"/g, "").replace(/^public\./, "");
const dirs = fs.readdirSync(migDir).filter((d) => fs.existsSync(path.join(migDir, d, "migration.sql"))).sort();

const T = new Map();
const t = (n) => { if (!T.has(n)) T.set(n, { rls: false, force: false, policies: new Set(), dropped: false }); return T.get(n); };
const fkNames = new Set();
const fnNames = new Set();
for (const d of dirs) {
  const sql = strip(fs.readFileSync(path.join(migDir, d, "migration.sql"), "utf8"));
  for (const m of sql.matchAll(/CREATE TABLE (?:IF NOT EXISTS )?((?:"?public"?\.)?"?\w+"?)/gi)) { const x = t(unq(m[1])); x.dropped = false; }
  for (const m of sql.matchAll(/DROP TABLE (?:IF EXISTS )?((?:"?public"?\.)?"?\w+"?)/gi)) { if (T.has(unq(m[1]))) T.get(unq(m[1])).dropped = true; }
  for (const m of sql.matchAll(/ALTER TABLE (?:ONLY )?((?:"?public"?\.)?"?\w+"?)\s+(ENABLE|DISABLE|FORCE|NO FORCE) ROW LEVEL SECURITY/gi)) {
    const x = t(unq(m[1])); const op = m[2].toUpperCase();
    if (op === "ENABLE") x.rls = true; if (op === "DISABLE") x.rls = false;
    if (op === "FORCE") x.force = true; if (op === "NO FORCE") x.force = false;
  }
  for (const m of sql.matchAll(/DROP POLICY (?:IF EXISTS )?"?(\w+)"? ON ((?:"?public"?\.)?"?\w+"?)/gi)) t(unq(m[2])).policies.delete(m[1]);
  for (const m of sql.matchAll(/CREATE POLICY "?(\w+)"? ON ((?:"?public"?\.)?"?\w+"?)/gi)) t(unq(m[2])).policies.add(m[1]);
  for (const m of sql.matchAll(/ADD CONSTRAINT "(\w+_tenant_fkey)"/g)) fkNames.add(m[1]);
  for (const m of sql.matchAll(/CREATE OR REPLACE FUNCTION public\.(sec_c_\w+)\(/g)) fnNames.add(m[1]);
}
const live = [...T.entries()].filter(([, v]) => !v.dropped).sort(([a], [b]) => a.localeCompare(b));
const rlsTables = live.filter(([, v]) => v.rls && v.force).map(([n]) => n);
const rlsNoForce = live.filter(([, v]) => v.rls && !v.force).map(([n]) => n);
const nonRls = live.filter(([, v]) => !v.rls).map(([n]) => n);
const policies = live.flatMap(([n, v]) => [...v.policies].sort().map((p) => `${n}.${p}`));

const arr = (xs) => (xs.length ? `ARRAY[\n    ${xs.map((x) => `'${x.replace(/'/g, "''")}'`).join(",\n    ")}\n  ]::text[]` : `ARRAY[]::text[]`);

const sql = `-- GENERATED by scripts/security/gen-security-catalog.mjs — DO NOT EDIT BY HAND.
-- Regenerate after adding a migration; CI (sec-c-tenant-db-ci.yml) fails if stale.
--
-- sec(C) — READ-ONLY production security-catalog assertions.
--
-- Prints ONE row per assertion: id, PASS/FAIL, a count, and — only on FAIL —
-- the offending catalog identifiers (table / policy / role / constraint names).
-- It never selects a row of application data. The repository is public, so this
-- output is designed to be public too.
--
-- Expected state = the repository's migrations (${dirs.length} directories):
--   ${rlsTables.length} tables with RLS ENABLED + FORCED, ${nonRls.length} tables deliberately without RLS,
--   ${policies.length} statically-declared policies, ${fkNames.size} composite tenant FKs, ${fnNames.size} definer lookups.
-- Role groups checked: app_runtime, app_auth, app_admin, app_ctlplane and every
-- LOGIN member of them.

SET statement_timeout = '60s';
SET default_transaction_read_only = on;
BEGIN TRANSACTION READ ONLY;

WITH
expected_rls(t) AS (SELECT unnest(${arr(rlsTables)})),
expected_non_rls(t) AS (SELECT unnest(${arr(nonRls)})),
expected_policies(tp) AS (SELECT unnest(${arr(policies)})),
expected_migrations(m) AS (SELECT unnest(${arr(dirs)})),
expected_fks(c) AS (SELECT unnest(${arr([...fkNames].sort())})),
expected_fns(f) AS (SELECT unnest(${arr([...fnNames].sort())})),
tbl AS (
  SELECT c.oid, c.relname AS t, c.relrowsecurity AS rls, c.relforcerowsecurity AS force,
         pg_get_userbyid(c.relowner) AS owner
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p') AND c.relname <> '_prisma_migrations'
),
groups AS (
  SELECT oid, rolname FROM pg_roles WHERE rolname IN ('app_runtime', 'app_auth', 'app_admin', 'app_ctlplane')
),
app_roles AS (
  SELECT r.oid, r.rolname, r.rolsuper, r.rolbypassrls, r.rolcreaterole, r.rolcreatedb, r.rolreplication, r.rolcanlogin
    FROM pg_roles r
   WHERE r.oid IN (SELECT oid FROM groups)
      OR r.oid IN (SELECT m.member FROM pg_auth_members m WHERE m.roleid IN (SELECT oid FROM groups))
),
runtime_roles AS (
  SELECT oid, rolname FROM pg_roles WHERE rolname = 'app_runtime'
  UNION SELECT r.oid, r.rolname FROM pg_roles r JOIN pg_auth_members m ON m.member = r.oid
   WHERE m.roleid = (SELECT oid FROM pg_roles WHERE rolname = 'app_runtime')
),
results AS (
  -- A1: every app role and LOGIN member is NOSUPERUSER, NOBYPASSRLS, NOCREATEROLE, NOCREATEDB, NOREPLICATION.
  SELECT 'A1_app_roles_least_privilege_attributes' AS id,
         count(*) FILTER (WHERE rolsuper OR rolbypassrls OR rolcreaterole OR rolcreatedb OR rolreplication) AS bad,
         count(*) AS total,
         string_agg(rolname, ',' ORDER BY rolname) FILTER (WHERE rolsuper OR rolbypassrls OR rolcreaterole OR rolcreatedb OR rolreplication) AS detail
    FROM app_roles
  UNION ALL
  -- A1b: the four groups exist and at least one runtime LOGIN member exists.
  SELECT 'A1b_role_groups_present',
         (4 - (SELECT count(*) FROM groups)) + CASE WHEN EXISTS (SELECT 1 FROM app_roles a JOIN runtime_roles r ON r.oid = a.oid WHERE a.rolcanlogin) THEN 0 ELSE 1 END,
         (SELECT count(*) FROM groups),
         NULLIF(concat_ws(',',
           CASE WHEN NOT EXISTS (SELECT 1 FROM groups WHERE rolname='app_runtime') THEN 'missing:app_runtime' END,
           CASE WHEN NOT EXISTS (SELECT 1 FROM groups WHERE rolname='app_auth') THEN 'missing:app_auth' END,
           CASE WHEN NOT EXISTS (SELECT 1 FROM groups WHERE rolname='app_admin') THEN 'missing:app_admin' END,
           CASE WHEN NOT EXISTS (SELECT 1 FROM groups WHERE rolname='app_ctlplane') THEN 'missing:app_ctlplane' END,
           CASE WHEN NOT EXISTS (SELECT 1 FROM app_roles a JOIN runtime_roles r ON r.oid = a.oid WHERE a.rolcanlogin) THEN 'no_runtime_login' END), '')
  UNION ALL
  -- A1c: no app role owns a public table (non-owner; FORCE RLS would otherwise be the owner's to disable).
  SELECT 'A1c_app_roles_own_no_tables',
         count(*), (SELECT count(*) FROM tbl),
         string_agg(t.t || '@' || t.owner, ',' ORDER BY t.t)
    FROM tbl t WHERE t.owner IN (SELECT rolname FROM app_roles)
  UNION ALL
  -- A2: every expected table has RLS ENABLED and FORCED.
  SELECT 'A2_expected_tables_rls_forced',
         count(*) FILTER (WHERE tb.t IS NULL OR NOT tb.rls OR NOT tb.force),
         count(*),
         string_agg(e.t || CASE WHEN tb.t IS NULL THEN ':missing' WHEN NOT tb.rls THEN ':rls_off' ELSE ':no_force' END, ',' ORDER BY e.t)
           FILTER (WHERE tb.t IS NULL OR NOT tb.rls OR NOT tb.force)
    FROM expected_rls e LEFT JOIN tbl tb ON tb.t = e.t
  UNION ALL
  -- A3: no public table is without RLS unless the repository says so.
  SELECT 'A3_no_unexpected_non_rls_tables',
         count(*), (SELECT count(*) FROM tbl WHERE NOT rls),
         string_agg(tb.t, ',' ORDER BY tb.t)
    FROM tbl tb WHERE (NOT tb.rls OR NOT tb.force) AND tb.t NOT IN (SELECT t FROM expected_non_rls)
                      AND tb.t NOT IN (SELECT t FROM expected_rls)
  UNION ALL
  -- A4: every statically-declared policy exists.
  SELECT 'A4_expected_policies_present',
         count(*) FILTER (WHERE p.policyname IS NULL), count(*),
         string_agg(e.tp, ',' ORDER BY e.tp) FILTER (WHERE p.policyname IS NULL)
    FROM expected_policies e
    LEFT JOIN pg_policies p ON p.schemaname = 'public' AND p.tablename || '.' || p.policyname = e.tp
  UNION ALL
  -- A4b: USING (true) / unconditional policies apply only to app_admin (read) or a
  -- definer owner (sec_c_definer_lookup) — never to PUBLIC or a runtime role.
  SELECT 'A4b_unconditional_policies_scoped',
         count(*), (SELECT count(*) FROM pg_policies WHERE schemaname = 'public'),
         string_agg(p.tablename || '.' || p.policyname, ',' ORDER BY p.tablename)
    FROM pg_policies p
   WHERE p.schemaname = 'public'
     AND (p.qual = 'true' OR (p.qual IS NULL AND p.with_check IS NULL))
     AND NOT (p.roles = ARRAY['app_admin']::name[] AND p.cmd = 'SELECT')
     AND p.policyname <> 'sec_c_definer_lookup'
  UNION ALL
  -- A5: the runtime (group + members) holds no TRUNCATE/REFERENCES/TRIGGER anywhere,
  -- no read of User.password, and no INSERT on User/Business.
  SELECT 'A5_runtime_privilege_ceiling',
         count(*), (SELECT count(*) FROM runtime_roles),
         string_agg(DISTINCT x.what, ',' ORDER BY x.what)
    FROM (
      SELECT r.rolname || ':' || tb.t || ':' || p.priv AS what
        FROM runtime_roles r CROSS JOIN tbl tb CROSS JOIN unnest(ARRAY['TRUNCATE','REFERENCES','TRIGGER']) p(priv)
       WHERE has_table_privilege(r.oid, tb.oid, p.priv)
      UNION ALL
      SELECT r.rolname || ':User.password:SELECT' FROM runtime_roles r
       WHERE has_column_privilege(r.oid, '"User"', 'password', 'SELECT')
      UNION ALL
      SELECT r.rolname || ':' || x.t || ':INSERT' FROM runtime_roles r CROSS JOIN (VALUES ('User'), ('Business')) x(t)
       WHERE has_table_privilege(r.oid, format('%I', x.t), 'INSERT')
    ) x
  UNION ALL
  -- A5b: app_admin cannot read the password hash.
  SELECT 'A5b_admin_cannot_read_password',
         CASE WHEN EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_admin')
                   AND has_column_privilege('app_admin', '"User"', 'password', 'SELECT') THEN 1 ELSE 0 END,
         1, NULL
  UNION ALL
  -- A6: default-deny — no default ACL hands the runtime anything on new tables/sequences.
  SELECT 'A6_no_runtime_default_privileges',
         count(*), (SELECT count(*) FROM pg_default_acl),
         string_agg(DISTINCT pg_get_userbyid(d.defaclrole) || '->' || pg_get_userbyid(g.grantee) || ':' || d.defaclobjtype::text, ',')
    FROM pg_default_acl d CROSS JOIN LATERAL aclexplode(d.defaclacl) g
   WHERE g.grantee IN (SELECT oid FROM runtime_roles)
  UNION ALL
  -- A7: every repository migration is applied, finished and not rolled back; none failed.
  SELECT 'A7_migration_ledger_complete',
         (SELECT count(*) FROM expected_migrations e WHERE NOT EXISTS (
            SELECT 1 FROM _prisma_migrations m WHERE m.migration_name = e.m AND m.finished_at IS NOT NULL AND m.rolled_back_at IS NULL))
         + (SELECT count(*) FROM _prisma_migrations m WHERE m.finished_at IS NULL AND m.rolled_back_at IS NULL),
         (SELECT count(*) FROM expected_migrations),
         (SELECT string_agg(e.m, ',' ORDER BY e.m) FROM expected_migrations e WHERE NOT EXISTS (
            SELECT 1 FROM _prisma_migrations m WHERE m.migration_name = e.m AND m.finished_at IS NOT NULL AND m.rolled_back_at IS NULL))
  UNION ALL
  -- A8: composite tenant FKs exist and are VALIDATED (NOT VALID = legacy cross-tenant rows exist).
  SELECT 'A8_tenant_fks_present_and_validated',
         count(*) FILTER (WHERE c.oid IS NULL OR NOT c.convalidated), count(*),
         string_agg(e.c || CASE WHEN c.oid IS NULL THEN ':missing' ELSE ':not_valid' END, ',' ORDER BY e.c)
           FILTER (WHERE c.oid IS NULL OR NOT c.convalidated)
    FROM expected_fks e LEFT JOIN pg_constraint c ON c.conname = e.c AND c.contype = 'f'
  UNION ALL
  -- A9: definer lookups are SECURITY DEFINER, search_path-pinned, and not executable by PUBLIC.
  SELECT 'A9_definer_lookups_hardened',
         count(*) FILTER (WHERE p.oid IS NULL OR NOT p.prosecdef
                          OR NOT coalesce(array_to_string(p.proconfig, ',') LIKE '%search_path=%', false)
                          OR has_function_privilege('public', p.oid, 'EXECUTE')),
         count(*),
         string_agg(e.f, ',' ORDER BY e.f) FILTER (WHERE p.oid IS NULL OR NOT p.prosecdef
                          OR NOT coalesce(array_to_string(p.proconfig, ',') LIKE '%search_path=%', false)
                          OR has_function_privilege('public', p.oid, 'EXECUTE'))
    FROM expected_fns e
    LEFT JOIN pg_proc p ON p.proname = e.f AND p.pronamespace = 'public'::regnamespace
)
SELECT id, CASE WHEN bad = 0 THEN 'PASS' ELSE 'FAIL' END AS result, bad AS failing, total AS checked,
       CASE WHEN bad = 0 THEN NULL ELSE left(detail, 2000) END AS failing_identifiers
  FROM results
 ORDER BY id;

ROLLBACK;
`;

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== sql) {
    console.error("STALE: ops/evidence/security-catalog-assert.sql does not match the migrations — run node scripts/security/gen-security-catalog.mjs");
    process.exit(1);
  }
  console.log(`security catalog manifest up to date (${dirs.length} migrations, ${rlsTables.length} RLS tables, ${policies.length} policies)`);
} else {
  fs.writeFileSync(OUT, sql);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${dirs.length} migrations, ${rlsTables.length} RLS+FORCE, ${nonRls.length} non-RLS, ${policies.length} policies, ${fkNames.size} FKs, ${fnNames.size} fns`);
}
